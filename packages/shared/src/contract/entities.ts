import { z } from 'zod';

const uuid = z.uuid();
const ts = z.iso.datetime();
const tiptapDoc = z.looseObject({
  type: z.literal('doc'),
  content: z.array(z.unknown()).optional(),
});

export const entitySchemas = {
  users: z.object({
    id: uuid,
    login: z.string(),
    name: z.string(),
    email: z.string().nullable(),
    role: z.enum(['owner', 'admin', 'member', 'guest']),
    avatarFile: z.string().nullable(),
    deactivatedAt: ts.nullable(),
    createdAt: ts,
    updatedAt: ts,
  }),
  spaces: z.object({
    id: uuid,
    name: z.string(),
    description: z.string().nullable(),
    color: z.string().nullable(),
    icon: z.string().nullable(),
    rank: z.string().min(1),
    createdBy: uuid,
    createdAt: ts,
    updatedAt: ts,
  }),
  spaceMembers: z.object({
    id: uuid,
    spaceId: uuid,
    userId: uuid,
    role: z.enum(['admin', 'member', 'guest']),
    createdAt: ts,
    updatedAt: ts,
  }),
  projects: z.object({
    id: uuid,
    spaceId: uuid,
    name: z.string(),
    key: z.string(),
    description: tiptapDoc.nullable(),
    color: z.string().nullable(),
    icon: z.string().nullable(),
    leadId: uuid.nullable(),
    rank: z.string().min(1),
    archivedAt: ts.nullable(),
    createdAt: ts,
    updatedAt: ts,
  }),
  statuses: z.object({
    id: uuid,
    spaceId: uuid,
    name: z.string(),
    category: z.enum(['backlog', 'todo', 'in_progress', 'done', 'cancelled']),
    color: z.string(),
    rank: z.string().min(1),
    createdAt: ts,
    updatedAt: ts,
  }),
  tasks: z.object({
    id: uuid,
    spaceId: uuid,
    projectId: uuid,
    number: z.number().int().nullable(),
    parentId: uuid.nullable(),
    statusId: uuid,
    title: z.string(),
    description: tiptapDoc.nullable(),
    priority: z.number().int(),
    rank: z.string().min(1),
    dueDate: z.iso.date().nullable(),
    startDate: z.iso.date().nullable(),
    createdBy: uuid,
    completedAt: ts.nullable(),
    fields: z.record(z.string(), z.unknown()),
    cycleId: uuid.nullable(),
    createdAt: ts,
    updatedAt: ts,
  }),
  taskAssignees: z.object({
    id: uuid,
    spaceId: uuid,
    taskId: uuid,
    userId: uuid,
    createdAt: ts,
  }),
  taskWatchers: z.object({
    id: uuid,
    spaceId: uuid,
    taskId: uuid,
    userId: uuid,
    createdAt: ts,
  }),
  labels: z.object({
    id: uuid,
    spaceId: uuid,
    name: z.string(),
    color: z.string(),
    createdAt: ts,
    updatedAt: ts,
  }),
  taskLabels: z.object({
    id: uuid,
    spaceId: uuid,
    taskId: uuid,
    labelId: uuid,
    createdAt: ts,
  }),
  fieldDefs: z.object({
    id: uuid,
    spaceId: uuid,
    projectId: uuid,
    name: z.string().min(1).max(100),
    type: z.enum(['text', 'number', 'date', 'select', 'user', 'url', 'money']),
    options: z.record(z.string(), z.unknown()),
    rank: z.string().min(1),
    createdAt: ts,
    updatedAt: ts,
  }),
  taskLinks: z.object({
    id: uuid,
    spaceId: uuid,
    taskId: uuid,
    targetId: uuid,
    kind: z.enum(['blocks', 'relates', 'duplicates']),
    createdBy: uuid,
    createdAt: ts,
  }),
  checklistItems: z.object({
    id: uuid,
    spaceId: uuid,
    taskId: uuid,
    text: z.string(),
    done: z.boolean(),
    rank: z.string().min(1),
    createdAt: ts,
    updatedAt: ts,
  }),
  comments: z.object({
    id: uuid,
    spaceId: uuid,
    taskId: uuid,
    authorId: uuid,
    body: tiptapDoc,
    mentions: z.array(uuid),
    editedAt: ts.nullable(),
    createdAt: ts,
    updatedAt: ts,
  }),
  commentReactions: z.object({
    id: uuid,
    spaceId: uuid,
    commentId: uuid,
    userId: uuid,
    emoji: z.string().min(1).max(32),
    createdAt: ts,
  }),
  attachments: z.object({
    id: uuid,
    spaceId: uuid,
    taskId: uuid,
    commentId: uuid.nullable(),
    fileSha256: z.string(),
    name: z.string(),
    mime: z.string(),
    size: z.number().int(),
    width: z.number().int().nullable(),
    height: z.number().int().nullable(),
    uploadedBy: uuid,
    createdAt: ts,
  }),
  activity: z.object({
    id: uuid,
    spaceId: uuid,
    taskId: uuid,
    actorId: uuid,
    kind: z.enum([
      'created',
      'updated',
      'deleted',
      'assignee_added',
      'assignee_removed',
      'label_added',
      'label_removed',
      'commented',
    ]),
    changes: z.record(z.string(), z.unknown()),
    viaTokenId: uuid.nullable(),
    createdAt: ts,
  }),
  notifications: z.object({
    id: uuid,
    userId: uuid,
    spaceId: uuid,
    kind: z.enum(['assigned', 'mentioned', 'commented', 'status_changed']),
    taskId: uuid,
    commentId: uuid.nullable(),
    actorId: uuid,
    readAt: ts.nullable(),
    createdAt: ts,
  }),
  savedViews: z.object({
    id: uuid,
    spaceId: uuid,
    userId: uuid.nullable(),
    createdBy: uuid,
    name: z.string(),
    layout: z.string(),
    filter: z.record(z.string(), z.unknown()),
    config: z.record(z.string(), z.unknown()),
    rank: z.string().min(1),
    createdAt: ts,
    updatedAt: ts,
  }),
  settings: z.object({
    id: z.string(),
    value: z.json(),
    updatedAt: ts,
  }),
} as const;

export interface EntityMeta {
  scope: string;
  write: string;
  bootstrap: boolean;
  indexes: string[];
  /** scope 'space|members' (C-sync v2): участники контейнера строки без spaceId */
  members?: { entity: string; key: string; container: string; via: string };
}

